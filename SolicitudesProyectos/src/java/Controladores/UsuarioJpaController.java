    /**
     * Valida las credenciales de ingreso al sistema.
     *
     * Los parametros van por setParameter y NO concatenados dentro del CALL.
     * Este es el unico punto del sistema al que se llega sin estar autenticado:
     * concatenar el usuario permitia cerrar la comilla desde el formulario de
     * login y alterar la sentencia. El driver escapa el valor y lo envia como
     * dato, nunca como parte del SQL.
     *
     * sp_usa_login declara sus dos parametros como VARCHAR(45) latin1, asi que
     * el String de Java mapea directo y no hace falta introductor de charset.
     *
     * @param user nombre de usuario tal como se escribio en el formulario
     * @param contra contrasena en texto plano o su hash MD5; el Servlet prueba
     *        las dos formas porque conviven usuarios migrados y sin migrar
     * @return la fila del usuario, o null si no hay coincidencia
     * @see sp_usa_login
     */
    public List login(String user, String contra) {
        EntityManager em = getEntityManager();
        try {
            em.getTransaction().begin();
            Query q = em.createNativeQuery("CALL `sp_usa_login`(?,?)");
            q.setParameter(1, user);
            q.setParameter(2, contra);
            List resultados = q.getResultList();
            em.getTransaction().commit();
            em.clear();
            em.close();
            if (!resultados.isEmpty()) {
                return resultados;
            } else {
                return null;
            }
        } catch (Exception e) {
            return null;
        } finally {
            // Rollback ANTES de cerrar. Si la consulta fallo, la transaccion
            // queda abierta y EclipseLink descarta la conexion en vez de
            // devolverla al pool: medido, cada consulta fallida quemaba una
            // conexion para siempre hasta agotar max_connections. Cerrar en el
            // finally no alcanza; hay que deshacer la transaccion primero.
            // En el camino exitoso el commit ya cerro la transaccion y este
            // bloque no hace nada.
            if (em.isOpen()) {
                if (em.getTransaction().isActive()) {
                    em.getTransaction().rollback();
                }
                em.close();
            }
        }
    }

